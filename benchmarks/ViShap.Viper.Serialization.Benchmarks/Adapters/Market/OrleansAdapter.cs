using System.Buffers;
using Microsoft.Extensions.DependencyInjection;
using Orleans.Serialization;
using Orleans.Serialization.Session;
using Orleans.Serialization.Utilities;
using ViShap.Viper.Serialization.Benchmarks.Capabilities;
using ViShap.Viper.Serialization.Benchmarks.DataSets;
using ViShap.Viper.Serialization.Benchmarks.Models;

namespace ViShap.Viper.Serialization.Benchmarks.Adapters.Market;

/// <summary>
/// Microsoft.Orleans.Serialization standalone: <c>[GenerateSerializer]</c> models with <c>[Id(n)]</c>
/// members, whose codecs the Orleans code generator writes at build time, through the
/// <see cref="Serializer"/> a service provider with <c>AddSerializer()</c> hands out.
/// </summary>
internal sealed class OrleansAdapter : MarketAdapter, IBufferWriterSerializer, ISpanDeserializer
{
    private readonly ServiceProvider _services;
    private readonly Serializer _serializer;

    internal OrleansAdapter()
        : base("Microsoft.Orleans.Serialization", typeof(Serializer).Assembly, "default", ModelFamily.Orleans, Tier.T1 | Tier.T2 | Tier.T3)
    {
        _services = new ServiceCollection().AddSerializer().BuildServiceProvider();
        _serializer = _services.GetRequiredService<Serializer>();
    }

    internal override Rationale Rationale => new(
        "Source generator: [GenerateSerializer] and [Id(n)], codecs generated by Microsoft.Orleans.CodeGenerator (\"Serialization in Orleans\", \"Use Orleans serialization outside Orleans\")",
        "new ServiceCollection().AddSerializer(); the Serializer it registers, with its defaults",
        "No type-name allow list or copier is configured: generated types are known to the serializer, and nothing is copied",
        "None known to this harness: the generated codecs through Serializer are the documented path");

    internal override IReadOnlyList<Limitation> Limitations =>
    [
        new("DATA-19", "LinkedList`1", "no codec for LinkedList<T>"),
        new("DATA-20", "System.Numerics.Complex", "no codec for System.Numerics.Complex"),
    ];

    public override byte[] Serialize<T>(T value) => _serializer.SerializeToArray(value);

    public override T? Deserialize<T>(byte[] payload) where T : default => _serializer.Deserialize<T>(payload);

    public override void Serialize<T>(Stream destination, T value) => _serializer.Serialize(value, destination);

    public override T? Deserialize<T>(Stream source) where T : default => _serializer.Deserialize<T>(source);

    public void Serialize<T>(IBufferWriter<byte> destination, T value) => _serializer.Serialize(value, destination);

    public T? Deserialize<T>(ReadOnlySequence<byte> payload) => _serializer.Deserialize<T>(payload);

    public T? Deserialize<T>(ReadOnlySpan<byte> payload) => _serializer.Deserialize<T>(payload);

    internal override ProbeOutcome SelfDescription()
    {
        var payload = Serialize(new Models.OrleansVariant.ProbeRecord { A = 7, B = "self-described", C = 2.5 });
        using var session = _services.GetRequiredService<SerializerSessionPool>().GetSession();
        var text = BitStreamFormatter.Format(payload, session);

        return Probes.ValuesOnly($"field ids and wire types, formatted by BitStreamFormatter into {text.Length} characters", payload.Length);
    }
}
